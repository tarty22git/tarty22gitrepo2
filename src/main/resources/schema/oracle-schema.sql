-- Oracle Schema
CREATE TABLE USERS (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR2(50) UNIQUE NOT NULL,
    PASSWORD VARCHAR2(255) NOT NULL,
    EMAIL VARCHAR2(100) NOT NULL,
    PHONE_NUMBER VARCHAR2(20),
    ROLE VARCHAR2(20) NOT NULL,
    ENABLED NUMBER(1) DEFAULT 1,
    LOCKED NUMBER(1) DEFAULT 0,
    FAILED_ATTEMPTS NUMBER(10) DEFAULT 0,
    PASSWORD_LAST_UPDATED TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    OTP_CODE VARCHAR2(10),
    OTP_EXPIRY TIMESTAMP,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE RECON_JOB_STATS (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    JOB_NAME VARCHAR2(100) NOT NULL,
    FILE1_NAME VARCHAR2(255),
    FILE2_NAME VARCHAR2(255),
    MATCHED_COUNT NUMBER(10) DEFAULT 0,
    UNMATCHED_COUNT NUMBER(10) DEFAULT 0,
    STATUS VARCHAR2(20),
    EXECUTED_BY VARCHAR2(50),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE APP_CONFIG (
    CONFIG_KEY VARCHAR2(50) PRIMARY KEY,
    CONFIG_VALUE VARCHAR2(255) NOT NULL
);
