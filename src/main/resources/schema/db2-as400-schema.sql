-- DB2 for AS400 Schema
CREATE TABLE USERS (
    ID BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    USERNAME VARCHAR(50) NOT NULL UNIQUE,
    PASSWORD VARCHAR(255) NOT NULL,
    EMAIL VARCHAR(100) NOT NULL,
    PHONE_NUMBER VARCHAR(20),
    ROLE VARCHAR(20) NOT NULL,
    ENABLED CHAR(1) DEFAULT 'Y',
    LOCKED CHAR(1) DEFAULT 'N',
    FAILED_ATTEMPTS INT DEFAULT 0,
    PASSWORD_LAST_UPDATED TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    OTP_CODE VARCHAR(10),
    OTP_EXPIRY TIMESTAMP,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (ID)
);

CREATE TABLE RECON_JOB_STATS (
    ID BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    JOB_NAME VARCHAR(100) NOT NULL,
    FILE1_NAME VARCHAR(255),
    FILE2_NAME VARCHAR(255),
    MATCHED_COUNT INT DEFAULT 0,
    UNMATCHED_COUNT INT DEFAULT 0,
    STATUS VARCHAR(20),
    EXECUTED_BY VARCHAR(50),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (ID)
);

CREATE TABLE APP_CONFIG (
    CONFIG_KEY VARCHAR(50) NOT NULL PRIMARY KEY,
    CONFIG_VALUE VARCHAR(255) NOT NULL
);
